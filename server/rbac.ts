export function isPlatformSuperAdmin(user: Pick<User, 'email' | 'is_super_admin'>): boolean {
  return (
    user.is_super_admin === true ||
    user.email.trim().toLowerCase() === BOOTSTRAP_SUPER_ADMIN_EMAIL
  );
}

export function getEffectivePermissions(
  membership: UserMembership,
  user: Pick<User, 'email' | 'is_super_admin'>
): PermissionCode[] {
  const set = new Set<PermissionCode>(ROLE_PERMISSIONS[membership.role] ?? []);
  if (Array.isArray(membership.customPermissions)) {
    for (const p of membership.customPermissions) {
      set.add(p);
    }
  }
  if (isPlatformSuperAdmin(user)) {
    set.add('platform.manage');
    for (const p of ALL_TENANT_PERMISSIONS) {
      set.add(p);
    }
  }
  return Array.from(set);
}

export function canAccessOrganisation(
  membership: UserMembership,
  orgId: string
): boolean {
  if (!orgId) return false;
  if (membership.orgAccessMode === 'all') return true;
  return Array.isArray(membership.allowedOrgIds) && membership.allowedOrgIds.includes(orgId);
}

export function canViewInternalTicketNotes(permissions: PermissionCode[]): boolean {
  return permissions.includes('tickets.internal_notes');
}
